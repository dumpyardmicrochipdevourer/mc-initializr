export function translate(language, key, ...args) {
  const dictionary = translations[language] || translations.en;
  const text = dictionary[key] ?? translations.en[key] ?? key;
  return text.replace(/\{(\d+)\}/g, (_, index) => String(args[Number(index)] ?? ''));
}

export function pickLanguage(saved, browserLanguage = '') {
  if (saved === 'ru' || saved === 'en') return saved;
  return /^(ru|uk|be|kk)\b/i.test(browserLanguage) ? 'ru' : 'en';
}
